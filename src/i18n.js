function getMessage(dictionary, key) {
  return key.split('.').reduce((value, segment) => value?.[segment], dictionary)
}

export function t(key, values = {}) {
  const message =
    getMessage(messages[locale.value], key) ??
    getMessage(interfaceMessages[locale.value], key) ??
    getMessage(messages.en, key) ??
    getMessage(interfaceMessages.en, key) ??
    key

  return typeof message === 'string'
    ? message.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`)
    : message
}
